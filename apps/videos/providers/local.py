"""
OPS-01: local video storage on the application's own hosting (NetPoa cPanel first; Bunny Stream stays
available as an optional provider).

* Files live under VIDEO_LOCAL_ROOT (outside the public document root and the release folder; default
  ``<project>/private/videos``): ``media/<id>.mp4`` and ``thumbnails/<id>.<jpg|png>``. ``<id>`` is a
  random 32-hex identifier generated by ClipCash, never a user-supplied name, so no path can escape.
* Playback is a signed, expiring URL to ClipCash's own streaming view (apps.videos.media), which binds
  the token to the signed-in viewer and re-checks access on every request; there is no permanent public
  URL. The view streams in small chunks with HTTP Range support (seeking) and can hand the transfer to
  the web server (X-Sendfile style) when the hosting supports it.
* No FFmpeg or other system dependency: the duration is read from the MP4 header (pure Python) and
  thumbnails are optional uploaded images.
"""

import re
import struct
import uuid
from datetime import timedelta
from pathlib import Path

from django.conf import settings
from django.core import signing
from django.urls import reverse
from django.utils import timezone

from .base import Playback, ProviderPermanentError, ProviderVideoInfo

ID_PATTERN = re.compile(r"^[0-9a-f]{32}$")
TOKEN_SALT = "videos.local.media"


class LocalStorageProvider:
    code = "LOCAL"

    def __init__(self, *, root):
        self.root = Path(root)

    def __repr__(self):
        return "<LocalStorageProvider>"

    # --- Paths ----------------------------------------------------------------------------------

    @staticmethod
    def new_id():
        return uuid.uuid4().hex

    def media_path(self, video_id):
        if not ID_PATTERN.match(str(video_id or "")):
            raise ProviderPermanentError("Invalid local video identifier.")
        return self.root / "media" / f"{video_id}.mp4"

    def thumbnail_path(self, video_id, thumbnail_file):
        name = str(thumbnail_file or "")
        if not re.match(rf"^{re.escape(str(video_id))}\.(jpg|png)$", name) or not ID_PATTERN.match(str(video_id)):
            raise ProviderPermanentError("Invalid local thumbnail.")
        return self.root / "thumbnails" / name

    def usage_bytes(self):
        total = 0
        for folder in ("media", "thumbnails"):
            base = self.root / folder
            if base.is_dir():
                total += sum(entry.stat().st_size for entry in base.iterdir() if entry.is_file())
        return total

    # --- Provider interface -------------------------------------------------------------------------

    def create_video(self, title):
        return self.new_id()

    def get_video(self, video_id):
        try:
            present = self.media_path(video_id).is_file()
        except ProviderPermanentError:
            present = False
        return ProviderVideoInfo(processing="READY" if present else "FAILED",
                                 error="" if present else "The video file is missing from storage.")

    def delete_video(self, video_id):
        path = self.media_path(video_id)
        path.unlink(missing_ok=True)
        for extension in ("jpg", "png"):
            (self.root / "thumbnails" / f"{video_id}.{extension}").unlink(missing_ok=True)

    def upload_authorization(self, video_id, **kwargs):
        raise ProviderPermanentError("Local videos are uploaded through the console upload form.")

    def playback(self, video_id, *, expires_in, viewer=None):
        seconds = max(int(expires_in or 0), settings.VIDEO_LOCAL_TOKEN_SECONDS)
        token = signing.dumps({"id": str(video_id), "u": str(viewer.pk) if viewer is not None else ""},
                              salt=TOKEN_SALT, compress=True)
        url = reverse("videos:media", args=[video_id]) + f"?t={token}"
        return Playback(kind="video", url=url, expires_at=timezone.now() + timedelta(seconds=seconds))

    def thumbnail_url(self, video_id, thumbnail_file, *, expires_in):
        if not thumbnail_file:
            return ""
        token = signing.dumps({"id": str(video_id), "u": "", "thumb": True}, salt=TOKEN_SALT, compress=True)
        return reverse("videos:media_thumbnail", args=[video_id]) + f"?t={token}"


def read_token(token, video_id, *, max_age):
    """The signed payload for this video, or None (bad signature, expired or another video)."""
    try:
        data = signing.loads(token or "", salt=TOKEN_SALT, max_age=max_age)
    except signing.BadSignature:
        return None
    return data if isinstance(data, dict) and data.get("id") == str(video_id) else None


# --- MP4 header reading (duration without FFmpeg) --------------------------------------------------

def looks_like_mp4(head):
    """An ISO base media file starts with a box of type 'ftyp' (bytes 4..8)."""
    return len(head) >= 12 and head[4:8] == b"ftyp"


def mp4_duration_seconds(path, *, max_boxes=4096):
    """Movie duration in whole seconds, or None when the header cannot tell (the uploader's browser
    measurement is used then). Reads box headers only (seeks), never the media data.

    * Normal MP4: the 'mvhd' duration.
    * Fragmented MP4 (has 'mvex', e.g. made by a browser's recorder): 'mvhd' does not cover the
      fragments, so only the 'mehd' fragment duration is trusted; without it, None."""
    try:
        with open(path, "rb") as handle:
            size = handle.seek(0, 2)
            boxes = _moov_boxes(handle, size, budget=[max_boxes])
    except (OSError, struct.error, ValueError, IndexError):
        return None
    if boxes is None:
        return None
    timescale, duration, fragmented, fragment_duration = boxes
    if not timescale:
        return None
    if fragmented:
        duration = fragment_duration
    if not duration or duration in (0xFFFFFFFF, 0xFFFFFFFFFFFFFFFF):
        return None
    return max(1, round(duration / timescale))


def _box_header(handle, position, end):
    handle.seek(position)
    header = handle.read(8)
    if len(header) < 8:
        return None
    box_size, box_type = struct.unpack(">I4s", header)
    offset = 8
    if box_size == 1:
        box_size = struct.unpack(">Q", handle.read(8))[0]
        offset = 16
    elif box_size == 0:
        box_size = end - position
    if box_size < offset:
        return None
    return box_size, box_type, offset


def _children(handle, start, end, budget):
    position = start
    while position + 8 <= end and budget[0] > 0:
        budget[0] -= 1
        header = _box_header(handle, position, end)
        if header is None:
            return
        box_size, box_type, offset = header
        yield box_type, position + offset, position + box_size
        position += box_size


def _full_box_version(handle, start):
    """Version of a 'full box' (version 1 uses 64-bit times and durations); leaves the file after its flags."""
    handle.seek(start)
    version = handle.read(1)[0]
    handle.read(3)
    return version


def _moov_boxes(handle, size, *, budget):
    for box_type, start, end in _children(handle, 0, size, budget):
        if box_type != b"moov":
            continue
        timescale = duration = fragment_duration = None
        fragmented = False
        for child, child_start, child_end in _children(handle, start, end, budget):
            if child == b"mvhd":
                version = _full_box_version(handle, child_start)
                if version == 1:
                    handle.read(16)
                    timescale, duration = struct.unpack(">IQ", handle.read(12))
                else:
                    handle.read(8)
                    timescale, duration = struct.unpack(">II", handle.read(8))
            elif child == b"mvex":
                fragmented = True
                for grandchild, g_start, _g_end in _children(handle, child_start, child_end, budget):
                    if grandchild == b"mehd":
                        version = _full_box_version(handle, g_start)
                        fragment_duration = struct.unpack(">Q" if version == 1 else ">I",
                                                          handle.read(8 if version == 1 else 4))[0]
        return timescale, duration, fragmented, fragment_duration
    return None
